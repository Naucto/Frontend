// Bundles the AudioWorklet processor into a string module so the engine can load
// it from a Blob URL without any bundler configuration in the consuming app.
import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const entry = resolve(root, 'src/sound/worklet/synth.worklet.ts');
// npm runs this as the package's prepare script, which also fires in Docker's
// dependency layer where only the manifests are copied: nothing to build yet.
if (!existsSync(entry)) {
  console.warn('build-worklet: worklet source not present, skipping');
  process.exit(0);
}
const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'iife',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
});
const code = result.outputFiles[0].text;
const out = `// GENERATED by scripts/build-worklet.mjs — do not edit.\nexport const SYNTH_WORKLET_SOURCE = ${JSON.stringify(code)};\n`;
await writeFile(resolve(root, 'src/sound/worklet/synth.worklet.generated.ts'), out);
console.warn(`build-worklet: ${(code.length / 1024).toFixed(1)} KB`);
